#!/usr/bin/env python3
"""Build the fonts the PDF writer embeds: subset to Latin + Cyrillic, convert CFF->TrueType, print width tables.
usage: python3 scripts/make-pdf-font.py REGULAR.(otf|ttf) BOLD.(otf|ttf)
Writes src/lib/fonts/pdf-regular.ttf, pdf-bold.ttf and src/lib/pdf-metrics.js (glyph map and widths)."""
import sys, os
from fontTools.ttLib import TTFont, newTable
from fontTools import subset
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.ttGlyphPen import TTGlyphPen

CP1252_EXTRA = '€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ'
CYR = ''.join(chr(c) for c in list(range(0x0400, 0x0460)) + [0x0490, 0x0491, 0x04E8, 0x04E9, 0x04AE, 0x04AF, 0x04A2, 0x04A3, 0x04BA, 0x04BB, 0x0492, 0x0493, 0x049A, 0x049B])
CHARS = ''.join(chr(c) for c in list(range(32, 127)) + list(range(160, 256))) + CP1252_EXTRA + '×≈·→№' + CYR + '\u2116\u2212\u2264\u2265\u00b1\u2022'

def to_ttf(font):
    if 'glyf' in font: return font
    order = font.getGlyphOrder(); gs = font.getGlyphSet(); glyf = {}
    for n in order:
        pen = TTGlyphPen(gs); gs[n].draw(Cu2QuPen(pen, 1.0, reverse_direction=True)); glyf[n] = pen.glyph()
    font['loca'] = newTable('loca'); t = font['glyf'] = newTable('glyf'); t.glyphOrder = order; t.glyphs = glyf
    del font['CFF ']
    if 'VORG' in font: del font['VORG']
    font.sfntVersion = '\x00\x01\x00\x00'
    font['head'].glyphDataFormat = 0
    mp = newTable('maxp'); mp.tableVersion = 0x00010000
    for a in ('maxZones','maxTwilightPoints','maxStorage','maxFunctionDefs','maxInstructionDefs','maxStackElements','maxSizeOfInstructions','maxComponentElements'): setattr(mp, a, 0)
    mp.maxZones = 1; mp.maxPoints = mp.maxContours = mp.maxCompositePoints = mp.maxCompositeContours = mp.maxComponentDepth = 0
    mp.numGlyphs = len(order); font['maxp'] = mp
    post = font['post']; post.formatType = 2.0; post.extraNames = []; post.mapping = {}; post.glyphOrder = order
    return font

def build(src, out):
    f = TTFont(src)
    opts = subset.Options(); opts.layout_features = []; opts.name_IDs = [1, 2, 4, 6]; opts.notdef_outline = True; opts.hinting = False; opts.drop_tables += ['DSIG', 'GSUB', 'GPOS', 'GDEF', 'kern']
    s = subset.Subsetter(opts); s.populate(text=CHARS); s.subset(f)
    f = to_ttf(f); f.save(out)
    f = TTFont(out); upm = f['head'].unitsPerEm; cmap = f.getBestCmap(); hm = f['hmtx']
    cm = {u: g for u, g in cmap.items() if u >= 32 and g in f.getGlyphOrder()}
    order = f.getGlyphOrder(); gid = {n: i for i, n in enumerate(order)}
    umap = {u: gid[g] for u, g in cm.items()}
    gw = {gid[g]: round(hm[g][0] * 1000 / upm) for g in set(cm.values())}
    gw[0] = round(hm[order[0]][0] * 1000 / upm)
    return {'cmap': umap, 'w': gw}, f

if __name__ == '__main__':
    reg, bold = sys.argv[1:3]
    here = os.path.join(os.path.dirname(__file__), '..', 'src', 'lib')
    w_reg, fr = build(reg, os.path.join(here, 'fonts', 'pdf-regular.ttf'))
    w_bold, fb = build(bold, os.path.join(here, 'fonts', 'pdf-bold.ttf'))
    def meta(f):
        h, os2 = f['head'], f['OS/2']; u = 1000 / h.unitsPerEm
        return dict(bbox=[round(h.xMin * u), round(h.yMin * u), round(h.xMax * u), round(h.yMax * u)], ascent=round(f['hhea'].ascent * u), descent=round(f['hhea'].descent * u), cap=round(getattr(os2, 'sCapHeight', 700) * u) or 700)
    import json
    open(os.path.join(here, 'pdf-metrics.js'), 'w').write(
      '// Glyph maps (unicode -> glyph id), glyph advance widths (1/1000 em) and font-descriptor data of the embedded PDF fonts — generated by scripts/make-pdf-font.py\n'
      f'export const GLYPHS = {{ regular: {json.dumps(w_reg, separators=(",", ":"))}, bold: {json.dumps(w_bold, separators=(",", ":"))} }};\n'
      f'export const FONT_META = {{ regular: {json.dumps(meta(fr))}, bold: {json.dumps(meta(fb))} }};\n')
    print('ok', os.path.getsize(os.path.join(here, 'fonts', 'pdf-regular.ttf')), os.path.getsize(os.path.join(here, 'fonts', 'pdf-bold.ttf')))
